#!/usr/bin/env python3
"""Writes the error screen's font for the bsod ROM (vb/bsod/font.h): the GB
games' 5x7 letters (gb/gfx.py), a byte a row (bit 4 the leftmost pixel), in
FONT_ORDER. The ROM lays its text out and draws it with them.

    python3 vb/bsod/make_font.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'gb'))
from gfx import FONT_5x7, FONT_C, FONT_ORDER  # noqa: E402

rows = []
for ch in FONT_ORDER:
    rows.append(', '.join(str(int(r, 2)) for r in FONT_5x7[ch]))
with open(os.path.join(HERE, 'font.h'), 'w') as f:
    f.write('/* Generated by vb/bsod/make_font.py from gb/gfx.py - do not edit. */\n')
    f.write(f'static const char FONT_CHARS[] = "{FONT_C}";\n')
    f.write(f'static const unsigned char font[{len(FONT_ORDER)}][7] = {{\n' + ''.join(f'    {{ {r} }},\n' for r in rows) + '};\n')
print('wrote', os.path.join(HERE, 'font.h'), len(FONT_ORDER), 'letters')
