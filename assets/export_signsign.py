# Exports the "Signsign" character from character.blend to a C
# header for the GelatoStation ROMs (ps1/common/signsign.h): its skeleton,
# its mesh (each vertex rigidly on one bone, relative to that bone's joint),
# triangles with texture coordinates and normals, and its texture as 15-bit
# PS1 colour.
#
#   blender -b assets/character.blend --python assets/export_signsign.py
#
# PS1 axes: x right, y down, z away from the camera; the character faces -z
# (towards the camera, like gfx_guy). Blender: x right, y forward, z up, and
# the character faces -y. So (x, y, z) -> (x, -z, y), which is a proper
# rotation (no mirroring).
import os
import bpy

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'ps1', 'common', 'signsign.h')
MESH, ARM = 'PS2_Signsign_Char', 'Armature_Signsign_Char'
HEIGHT = 335          # units tall at scale 16 (the height gfx_guy draws him at)
TEX = 128

arm = bpy.data.objects[ARM]
obj = bpy.data.objects[MESH]
me = obj.data
me.calc_loop_triangles()

# units per metre, from the mesh's height (it stands on z = 0)
zs = [(obj.matrix_world @ v.co).z for v in me.vertices]
K = HEIGHT / max(zs)


def ps(v):
    return (round(v.x * K), round(-v.z * K), round(v.y * K))


bones = list(arm.data.bones)
index = {b.name: i for i, b in enumerate(bones)}
heads = [arm.matrix_world @ b.head_local for b in bones]

# each vertex goes with the bone that has the most weight on it (the rig is rigid)
groups = {g.index: g.name for g in obj.vertex_groups}
vbone = []
for v in me.vertices:
    ws = sorted(((g.weight, groups[g.group]) for g in v.groups), reverse=True)
    vbone.append(index[ws[0][1]] if ws else index['Hips'])

# vertices sorted by bone, so each bone's run can be transformed in one go
order = sorted(range(len(me.vertices)), key=lambda i: vbone[i])
remap = {old: new for new, old in enumerate(order)}
verts = []
for i in order:
    p = obj.matrix_world @ me.vertices[i].co
    h = heads[vbone[i]]
    a, b = ps(p), ps(h)
    verts.append((a[0] - b[0], a[1] - b[1], a[2] - b[2]))
runs = []
for bi in range(len(bones)):
    idx = [n for n, i in enumerate(order) if vbone[i] == bi]
    runs.append((idx[0], len(idx)) if idx else (0, 0))

uv = me.uv_layers.active.data
faces = []
for t in me.loop_triangles:
    vs = [remap[t.vertices[k]] for k in range(3)]
    uvs = []
    for k in range(3):
        u, v = uv[t.loops[k]].uv
        uvs += [max(0, min(TEX - 1, round(u * TEX))), max(0, min(TEX - 1, round((1 - v) * TEX)))]
    n = obj.matrix_world.to_3x3() @ t.normal
    n.normalize()
    nn = (round(n.x * 4096), round(-n.z * 4096), round(n.y * 4096))
    # the face is lit as part of its first vertex's bone
    faces.append((vs, uvs, nn, vbone[order[vs[0]]]))

# faces grouped by bone too (each bone's faces are lit together)
faces.sort(key=lambda f: f[3])
fruns = []
for bi in range(len(bones)):
    idx = [n for n, f in enumerate(faces) if f[3] == bi]
    fruns.append((idx[0], len(idx)) if idx else (0, 0))

# skeleton: parent and the joint's offset from the parent's joint
skel = []
for i, b in enumerate(bones):
    p = index[b.parent.name] if b.parent else -1
    h = ps(heads[i])
    ph = ps(heads[p]) if p >= 0 else (0, 0, 0)
    skel.append((p, h[0] - ph[0], h[1] - ph[1], h[2] - ph[2]))

# texture: 15-bit BGR with the STP bit set (so black isn't transparent)
img = None
for n in obj.material_slots[0].material.node_tree.nodes:
    if n.type == 'TEX_IMAGE' and n.image:
        img = n.image
# each texel the average of the whole block of the image it covers (not one pixel
# of it: the PS1 shrinks textures without smoothing, and the face is small on
# screen, so single pixels made it speckled)
import numpy as np
w, h = img.size
px = np.array(img.pixels[:], dtype=np.float32).reshape(h, w, 4)[::-1, :, :3]   # (Blender's rows start at the bottom)
bh, bw = h // TEX, w // TEX
avg = px[:bh * TEX, :bw * TEX].reshape(TEX, bh, TEX, bw, 3).mean(axis=(1, 3))
# then softened a little (1-2-1 across and down): small on screen, the eyes' whites
# otherwise flicker as bright specks between frames
k = lambda a, ax: (np.roll(a, 1, ax) + 2 * a + np.roll(a, -1, ax)) / 4
avg = k(k(avg, 0), 1)
tex = []
for y in range(TEX):
    for x in range(TEX):
        r, g, b = (min(31, int(avg[y, x, c] * 31 + 0.5)) for c in range(3))
        tex.append(0x8000 | (b << 10) | (g << 5) | r)

with open(OUT, 'w') as f:
    f.write('/* Generated by assets/export_signsign.py from assets/character.blend - do not edit. */\n')
    f.write('#ifndef GELATO_SIGNSIGN_H\n#define GELATO_SIGNSIGN_H\n#include <stdint.h>\n\n')
    f.write(f'#define SIGN_BONES {len(bones)}\n#define SIGN_VERTS {len(verts)}\n#define SIGN_FACES {len(faces)}\n#define SIGN_TEX {TEX}\n\n')
    for i, b in enumerate(bones):
        f.write(f'#define SB_{b.name.upper()} {i}\n')
    f.write('\n/* parent, joint offset from the parent joint (x, y, z) */\n')
    f.write('static const int16_t sign_skel[SIGN_BONES][4] = {\n' + ''.join(f'    {{ {p}, {x}, {y}, {z} }},\n' for p, x, y, z in skel) + '};\n')
    f.write('/* each bone\'s vertices: first, count */\n')
    f.write('static const uint16_t sign_runs[SIGN_BONES][2] = {\n' + ''.join(f'    {{ {a}, {n} }},\n' for a, n in runs) + '};\n')
    f.write('/* each bone\'s faces: first, count */\n')
    f.write('static const uint16_t sign_fruns[SIGN_BONES][2] = {\n' + ''.join(f'    {{ {a}, {n} }},\n' for a, n in fruns) + '};\n')
    f.write('/* vertices, relative to their bone\'s joint */\n')
    f.write('static const int16_t sign_verts[SIGN_VERTS][3] = {\n' + ''.join(f'    {{ {x}, {y}, {z} }},\n' for x, y, z in verts) + '};\n')
    f.write('/* triangles: vertices a, b, c, the bone it\'s lit with */\n')
    f.write('static const uint16_t sign_faces[SIGN_FACES][4] = {\n' + ''.join(f'    {{ {v[0]}, {v[1]}, {v[2]}, {bn} }},\n' for v, _, _, bn in faces) + '};\n')
    f.write('static const uint8_t sign_uvs[SIGN_FACES][6] = {\n' + ''.join('    { ' + ', '.join(map(str, u)) + ' },\n' for _, u, _, _ in faces) + '};\n')
    f.write('static const int16_t sign_normals[SIGN_FACES][3] = {\n' + ''.join(f'    {{ {n[0]}, {n[1]}, {n[2]} }},\n' for _, _, n, _ in faces) + '};\n')
    f.write('static const uint16_t sign_tex[SIGN_TEX * SIGN_TEX] = {\n')
    for i in range(0, len(tex), 16):
        f.write('    ' + ', '.join(f'0x{t:04x}' for t in tex[i:i + 16]) + ',\n')
    f.write('};\n\n#endif\n')
print('wrote', OUT, len(verts), 'verts', len(faces), 'faces', len(bones), 'bones', 'K', K)
