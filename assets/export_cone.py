# Exports the team's PS1 ice cream cone (assets/ps1/gelato_cone.blend)
# to a C header for the GelatoStation ROMs (ps1/common/cone.h): flat-coloured
# triangles, each with its face's colour (from its material's name, "Name R,G,B")
# and its outward normal, drawn by gfx_mesh. The cone's triangles come first,
# then the scoops' (from CONE_SCOOPS on), so a ROM can draw just the scoops.
#
# Units: 1 Blender metre = 200 PS1 units. PS1 axes: x right,
# y down, z away; Blender's front (-y) faces the camera: (x, y, z) -> (x, -z, y).
#
#   blender -b assets/ps1/gelato_cone.blend --python assets/export_cone.py
import os
import re

import bmesh
import bpy
from mathutils import Vector

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'ps1', 'common', 'cone.h')
K = 200
obj = next(o for o in bpy.data.objects if o.type == 'MESH' and o.visible_get())
dg = bpy.context.evaluated_depsgraph_get()
me = obj.evaluated_get(dg).to_mesh()
bm = bmesh.new()
bm.from_mesh(me)
bmesh.ops.triangulate(bm, faces=bm.faces[:])
M = obj.matrix_world


def ps(v):
    w = M @ v
    return (round(w.x * K), round(-w.z * K), round(w.y * K))


def rgb(mat):
    m = re.search(r'(\d+)\s*,\s*(\d+)\s*,\s*(\d+)', mat.name if mat else '')
    return tuple(int(x) for x in m.groups()) if m else (200, 200, 200)


SCOOPY = ('scoop', 'cherry', 'stem')
verts, index, tris = [], {}, []
for f in bm.faces:
    mat = obj.data.materials[f.material_index] if f.material_index < len(obj.data.materials) else None
    ids = []
    for v in f.verts:
        p = ps(v.co)
        if p not in index:
            index[p] = len(verts)
            verts.append(p)
        ids.append(index[p])
    n = (M.to_3x3() @ f.normal).normalized()
    n = Vector((n.x, -n.z, n.y))   # (PS1 axes)
    a, b, c = (Vector(verts[i]) for i in ids)
    # gfx_mesh's winding (gfx_pyramid's): (b - a) x (c - a) points inwards
    if (b - a).cross(c - a).dot(n) > 0:
        ids[1], ids[2] = ids[2], ids[1]
    scoop = any(k in (mat.name.lower() if mat else '') for k in SCOOPY)
    tris.append((scoop, ids, rgb(mat), tuple(round(x * 4096) for x in n)))
tris.sort(key=lambda t: t[0])   # (the cone first, then the scoops)
first_scoop = next(i for i, t in enumerate(tris) if t[0])
with open(OUT, 'w') as f:
    f.write('/* Generated by assets/export_cone.py from assets/ps1/gelato_cone.blend - do not edit. */\n')
    f.write('#ifndef GELATO_CONE_H\n#define GELATO_CONE_H\n#include "gfx.h"\n\n')
    f.write(f'#define CONE_VERTS {len(verts)}\n#define CONE_TRIS {len(tris)}\n#define CONE_SCOOPS {first_scoop}   /* the first of the scoops\' triangles */\n\n')
    f.write('static const int16_t cone_v[CONE_VERTS][3] = {\n' + ''.join(f'    {{ {x}, {y}, {z} }},\n' for x, y, z in verts) + '};\n')
    f.write('static const uint16_t cone_f[CONE_TRIS][3] = {\n' + ''.join(f'    {{ {a}, {b}, {c} }},\n' for _, (a, b, c), _, _ in tris) + '};\n')
    f.write('static const uint8_t cone_rgb[CONE_TRIS][3] = {\n' + ''.join(f'    {{ {r}, {g}, {b} }},\n' for _, _, (r, g, b), _ in tris) + '};\n')
    f.write('static const int16_t cone_n[CONE_TRIS][3] = {\n' + ''.join(f'    {{ {x}, {y}, {z} }},\n' for _, _, _, (x, y, z) in tris) + '};\n')
    f.write('static const mesh_t cone_mesh = { cone_v, cone_f, cone_rgb, cone_n, CONE_VERTS, CONE_TRIS };\n\n#endif\n')
ys = [v[1] for v in verts]
print('wrote', OUT, len(verts), 'verts', len(tris), 'tris, scoops from', first_scoop, 'y', min(ys), max(ys))
