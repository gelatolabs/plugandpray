#!/usr/bin/env python3
"""Makes the License to Chill lives' heart for the GelatoStation
(ps1/common/heart.h): the classic heart curve as a flat outline of 16 points,
made solid (a front and a back joined by its sides), flat-coloured like the
team's meshes (see export_cone.py), in two colours: a life left and one lost.

    python3 assets/make_heart.py

PS1 axes: x right, y down, z away from the camera."""
import math
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'ps1', 'common', 'heart.h')
N = 16          # points round the outline
SCALE = 1.9     # the curve is about 32 across: about 60 units
DEPTH = 10      # half its thickness
LIFE, LOST = (255, 70, 120), (70, 45, 70)


def outline():
    pts = []
    for i in range(N):
        t = 2 * math.pi * i / N
        x = 16 * math.sin(t) ** 3
        y = 13 * math.cos(t) - 5 * math.cos(2 * t) - 2 * math.cos(3 * t) - math.cos(4 * t)
        pts.append((x * SCALE, -(y + 2) * SCALE))   # (y down; the middle a little lower, inside both lobes)
    return pts


def sub(a, b): return tuple(p - q for p, q in zip(a, b))
def cross(a, b): return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])
def dot(a, b): return sum(p * q for p, q in zip(a, b))
def unit(a):
    n = math.sqrt(dot(a, a)) or 1
    return tuple(p / n for p in a)


pts = outline()
verts = [(round(x), round(y), z) for z in (-DEPTH, DEPTH) for x, y in pts] + [(0, 0, -DEPTH), (0, 0, DEPTH)]
FC, BC = 2 * N, 2 * N + 1   # the middles of the front and back
tris = []   # (ids, outward normal)
for i in range(N):
    j = (i + 1) % N
    tris.append(((FC, i, j), (0, 0, -1)))                 # front (towards the camera)
    tris.append(((BC, N + j, N + i), (0, 0, 1)))          # back
    # the side between i and j: outwards, away from the middle
    mid = ((pts[i][0] + pts[j][0]) / 2, (pts[i][1] + pts[j][1]) / 2)
    e = (pts[j][0] - pts[i][0], pts[j][1] - pts[i][1])
    n = unit((e[1], -e[0], 0))
    if n[0] * mid[0] + n[1] * mid[1] < 0:
        n = tuple(-p for p in n)
    tris.append(((i, j, N + j), n))
    tris.append(((i, N + j, N + i), n))
out = []
for ids, n in tris:
    a, b, c = (verts[k] for k in ids)
    # gfx_mesh's winding: (b - a) x (c - a) points inwards
    if dot(cross(sub(b, a), sub(c, a)), n) > 0:
        ids = (ids[0], ids[2], ids[1])
    out.append((ids, tuple(round(p * 4096) for p in n)))

with open(OUT, 'w') as f:
    f.write('/* Generated by assets/make_heart.py - do not edit. */\n#ifndef GELATO_HEART_H\n#define GELATO_HEART_H\n#include "gfx.h"\n\n')
    f.write(f'#define HEART_VERTS {len(verts)}\n#define HEART_TRIS {len(out)}\n\n')
    f.write('static const int16_t heart_v[HEART_VERTS][3] = {\n' + ''.join(f'    {{ {x}, {y}, {z} }},\n' for x, y, z in verts) + '};\n')
    f.write('static const uint16_t heart_f[HEART_TRIS][3] = {\n' + ''.join(f'    {{ {a}, {b}, {c} }},\n' for (a, b, c), _ in out) + '};\n')
    f.write('static const int16_t heart_n[HEART_TRIS][3] = {\n' + ''.join(f'    {{ {x}, {y}, {z} }},\n' for _, (x, y, z) in out) + '};\n')
    for name, rgb in (('life', LIFE), ('lost', LOST)):
        f.write(f'static const uint8_t heart_{name}_rgb[HEART_TRIS][3] = {{\n' + ''.join(f'    {{ {rgb[0]}, {rgb[1]}, {rgb[2]} }},\n' for _ in out) + '};\n')
    f.write('/* a life left, and a life lost */\n')
    f.write('static const mesh_t heart_life = { heart_v, heart_f, heart_life_rgb, heart_n, HEART_VERTS, HEART_TRIS };\n')
    f.write('static const mesh_t heart_lost = { heart_v, heart_f, heart_lost_rgb, heart_n, HEART_VERTS, HEART_TRIS };\n\n#endif\n')
print('wrote', OUT, len(verts), 'verts', len(out), 'tris')
