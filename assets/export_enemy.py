# Exports the team's License to Chill enemies (assets/ps1/enemy.blend)
# to a C header for the GelatoStation (ps1/common/enemy.h):
# for each of the three variants (the collections "Enemy blue", "Enemy yellow
# (fast)" and "Enemy red (tough)"), its body and its two wings as flat-coloured
# meshes (like the cone's: see export_cone.py), each around its own origin, and
# where each wing's origin (its hinge, at the shoulder) is on the body.
#
# Units: 1 Blender metre = 200 PS1 units. PS1 axes: x right, y down, z away;
# Blender's front (-y) faces the camera: (x, y, z) -> (x, -z, y).
#
#   blender -b assets/ps1/enemy.blend --python assets/export_enemy.py
import os
import re

import bmesh
import bpy
from mathutils import Vector

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'ps1', 'common', 'enemy.h')
K = 200
# the variants, in the order of the game's enemy types (EN_BASIC, EN_ZIPPY, EN_BIG)
VARIANTS = [('blue', 'basic'), ('yellow', 'zippy'), ('red', 'big')]


def ps(v):
    return (round(v.x * K), round(-v.z * K), round(v.y * K))


def rgb(mat):
    m = re.search(r'(\d+)\s*,\s*(\d+)\s*,\s*(\d+)', mat.name if mat else '')
    return tuple(int(x) for x in m.groups()) if m else (200, 200, 200)


def mesh(obj):
    """obj's triangles around its own origin (its rotation and scale applied):
    (vertices, [(ids, colour, normal)])."""
    dg = bpy.context.evaluated_depsgraph_get()
    me = obj.evaluated_get(dg).to_mesh()
    bm = bmesh.new()
    bm.from_mesh(me)
    bmesh.ops.triangulate(bm, faces=bm.faces[:])
    M = obj.matrix_world.to_3x3()
    verts, index, tris = [], {}, []
    for f in bm.faces:
        mat = obj.data.materials[f.material_index] if f.material_index < len(obj.data.materials) else None
        ids = []
        for v in f.verts:
            p = ps(M @ v.co)
            if p not in index:
                index[p] = len(verts)
                verts.append(p)
            ids.append(index[p])
        n = (M @ f.normal).normalized()
        n = Vector((n.x, -n.z, n.y))   # (PS1 axes)
        a, b, c = (Vector(verts[i]) for i in ids)
        # gfx_mesh's winding (gfx_pyramid's): (b - a) x (c - a) points inwards
        if (b - a).cross(c - a).dot(n) > 0:
            ids[1], ids[2] = ids[2], ids[1]
        tris.append((ids, rgb(mat), tuple(round(x * 4096) for x in n)))
    bm.free()
    return verts, tris


def c_mesh(name, verts, tris):
    return (f'static const int16_t {name}_v[{len(verts)}][3] = {{\n' + ''.join(f'    {{ {x}, {y}, {z} }},\n' for x, y, z in verts) + '};\n'
            f'static const uint16_t {name}_f[{len(tris)}][3] = {{\n' + ''.join(f'    {{ {a}, {b}, {c} }},\n' for (a, b, c), _, _ in tris) + '};\n'
            f'static const uint8_t {name}_rgb[{len(tris)}][3] = {{\n' + ''.join(f'    {{ {r}, {g}, {b} }},\n' for _, (r, g, b), _ in tris) + '};\n'
            f'static const int16_t {name}_n[{len(tris)}][3] = {{\n' + ''.join(f'    {{ {x}, {y}, {z} }},\n' for _, _, (x, y, z) in tris) + '};\n'
            f'static const mesh_t {name} = {{ {name}_v, {name}_f, {name}_rgb, {name}_n, {len(verts)}, {len(tris)} }};\n\n')


out = ['/* Generated by assets/export_enemy.py from assets/ps1/enemy.blend - do not edit. */\n',
       '#ifndef GELATO_ENEMY_H\n#define GELATO_ENEMY_H\n#include "gfx.h"\n\n',
       '/* An enemy: its body (around its middle) and its wings (each around its hinge,\n'
       ' * at hinge_l / hinge_r on the body). */\n',
       'typedef struct {\n    const mesh_t *body, *wing_l, *wing_r;\n    int16_t hinge_l[3], hinge_r[3];\n} enemy_model_t;\n\n']
models = []
for colour, kind in VARIANTS:
    coll = next(c for c in bpy.data.collections if colour in c.name.lower())
    objs = list(coll.objects)
    body = next(o for o in objs if 'body' in o.name.lower())
    wing_l = next(o for o in objs if 'wing l' in o.name.lower())
    wing_r = next(o for o in objs if 'wing r' in o.name.lower())
    for part, o in (('body', body), ('wing_l', wing_l), ('wing_r', wing_r)):
        v, t = mesh(o)
        out.append(c_mesh(f'enemy_{kind}_{part}', v, t))
        print(coll.name, part, len(v), 'verts', len(t), 'tris')
    hl, hr = (ps(w.matrix_world.translation - body.matrix_world.translation) for w in (wing_l, wing_r))
    models.append(f'    {{ &enemy_{kind}_body, &enemy_{kind}_wing_l, &enemy_{kind}_wing_r, {{ {hl[0]}, {hl[1]}, {hl[2]} }}, {{ {hr[0]}, {hr[1]}, {hr[2]} }} }},   /* {coll.name} */\n')
out.append('/* by enemy type - 1 (EN_BASIC, EN_ZIPPY, EN_BIG) */\nstatic const enemy_model_t enemy_models[3] = {\n' + ''.join(models) + '};\n\n#endif\n')
with open(OUT, 'w') as f:
    f.write(''.join(out))
print('wrote', OUT)
