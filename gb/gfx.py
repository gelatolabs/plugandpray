def encode_tile(rows):
    assert len(rows) == 8, rows
    out = []
    for row in rows:
        assert len(row) == 8, row
        lo = hi = 0
        for i, ch in enumerate(row):
            v = 0 if ch == "." else int(ch)
            lo |= (v & 1) << (7 - i)
            hi |= ((v >> 1) & 1) << (7 - i)
        out += [lo, hi]
    return out


def split(rows, w, h):
    """Splits a w x h pixel image into 8x8 tiles, row-major."""
    assert len(rows) == h and all(len(r) == w for r in rows), rows
    return [[r[x:x + 8] for r in rows[y:y + 8]] for y in range(0, h, 8) for x in range(0, w, 8)]


def sprite16(rows):
    """16x16 image -> 4 tiles in 8x16 sprite order: L-top, L-bottom, R-top, R-bottom."""
    t = split(rows, 16, 16)
    return [t[0], t[2], t[1], t[3]]


def sprite_cols(rows, w, h):
    """w x h image (h multiple of 16) -> tiles for 8x16 sprites, column-major in 16px bands."""
    tiles = []
    for band in range(0, h, 16):
        for x in range(0, w, 8):
            tiles.append([r[x:x + 8] for r in rows[band:band + 8]])
            tiles.append([r[x:x + 8] for r in rows[band + 8:band + 16]])
    return tiles


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
    return "const uint8_t %s[] = {\n%s\n};\n" % (name, "\n".join(lines))


class Sheet:
    """Accumulates named tiles and writes assets.c / assets.h."""

    def __init__(self):
        self.groups = []  # (array name, [(define name or None, tiles)])

    def add_group(self, array, items):
        self.groups.append((array, items))

    def write(self, outdir, extra_h=""):
        import os
        h = ["#pragma once", "#include <stdint.h>", ""]
        c = ["/* Generated, do not edit. */", '#include "assets.h"', ""]
        for array, items in self.groups:
            data, idx = [], 0
            for name, tiles in items:
                if name:
                    h.append("#define %s %d" % (name, idx))
                for t in tiles:
                    data += encode_tile(t)
                idx += len(tiles)
            h.append("#define %s_COUNT %d" % (array.upper(), idx))
            h.append("extern const uint8_t %s[];" % array)
            c.append(c_array(array, data))
        h.append(extra_h)
        with open(os.path.join(outdir, "assets.h"), "w") as f:
            f.write("\n".join(h) + "\n")
        with open(os.path.join(outdir, "assets.c"), "w") as f:
            f.write("\n".join(c))
