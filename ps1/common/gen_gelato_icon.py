#!/usr/bin/env python3
"""Writes gelato_icon.h: the Gelato Labs icon (the round part of
web/public/img/gelato.png) as a 64x64 15-bit texture for the GelatoStation's
boot screen (ps1/common/boot.c). Transparent pixels are 0 (the GPU skips them)."""
import os
import struct
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'web', 'public', 'img', 'gelato.png')
N = 64


def read_png(path):
    d = open(path, 'rb').read()
    i, idat = 8, b''
    while i < len(d):
        n = struct.unpack('>I', d[i:i + 4])[0]
        t, c = d[i + 4:i + 8], d[i + 8:i + 8 + n]
        if t == b'IHDR':
            w, h, depth, ctype = struct.unpack('>IIBB', c[:10])
            assert depth == 8 and ctype == 6, 'expects 8-bit RGBA'
        elif t == b'IDAT':
            idat += c
        i += 12 + n
    raw, bpp = zlib.decompress(idat), 4
    stride, rows, prev, o = w * bpp, [], bytearray(w * bpp), 0
    for _ in range(h):
        f = raw[o]
        o += 1
        line = bytearray(raw[o:o + stride])
        o += stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if f == 1: line[x] = (line[x] + a) & 255
            elif f == 2: line[x] = (line[x] + b) & 255
            elif f == 3: line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(line)
        prev = line
    return w, h, rows


w, h, rows = read_png(SRC)
size = h   # the icon is the square at the left
out = []
for y in range(N):
    for x in range(N):
        # average the source pixels under this one (weighted by their alpha)
        x0, x1 = x * size // N, (x + 1) * size // N
        y0, y1 = y * size // N, (y + 1) * size // N
        r = g = b = a = cnt = 0
        for sy in range(y0, y1):
            for sx in range(x0, x1):
                p = rows[sy][sx * 4:sx * 4 + 4]
                r += p[0] * p[3]; g += p[1] * p[3]; b += p[2] * p[3]; a += p[3]; cnt += 1
        if a < 128 * cnt:
            out.append(0)
            continue
        r, g, b = (min(31, (v // a + 4) >> 3) for v in (r, g, b))
        out.append(0x8000 | (b << 10) | (g << 5) | r or 0x8000)
with open(os.path.join(HERE, 'gelato_icon.h'), 'w') as f:
    f.write('/* Generated by gen_gelato_icon.py from web/public/img/gelato.png - do not edit. */\n')
    f.write('#ifndef GELATO_ICON_H\n#define GELATO_ICON_H\n#include <stdint.h>\n\n#define GELATO_ICON %d\n' % N)
    f.write('static const uint16_t gelato_icon[GELATO_ICON * GELATO_ICON] = {\n')
    for i in range(0, len(out), 16):
        f.write('    ' + ', '.join('0x%04x' % v for v in out[i:i + 16]) + ',\n')
    f.write('};\n\n#endif\n')
print('wrote gelato_icon.h', sum(1 for v in out if v), 'opaque pixels')
