#!/usr/bin/env python3
"""Writes font5x7.h: the GelatoBoy's 5x7 letters (gb/gfx.py) as bitmasks, for
the GelatoStation's boot screen (ps1/common/boot.c), which draws them as pixels
and as blocks."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'gb'))
from gfx import FONT_5x7  # noqa: E402

chars = ''.join(c for c in FONT_5x7 if c != ' ')
with open(os.path.join(HERE, 'font5x7.h'), 'w') as f:
    f.write('/* Generated by gen_font5x7.py from gb/gfx.py - do not edit. */\n')
    f.write('#ifndef GELATO_FONT5X7_H\n#define GELATO_FONT5X7_H\n#include <stdint.h>\n\n')
    f.write('static const char font5x7_chars[] = "%s";\n' % chars.replace('"', '\\"'))
    f.write('/* per character, 7 rows top first, bit 4 the leftmost column */\n')
    f.write('static const uint8_t font5x7[][7] = {\n')
    for c in chars:
        f.write('    { ' + ', '.join('0x%02x' % int(r, 2) for r in FONT_5x7[c]) + ' },   /* %s */\n' % ('\\"' if c == '"' else c))
    f.write('};\n\n#endif\n')
print('wrote font5x7.h', len(chars), 'characters')
